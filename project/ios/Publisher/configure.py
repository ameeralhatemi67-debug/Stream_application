#!/usr/bin/env python3
"""Opt in to W17 without migrating Flutter's CocoaPods integration. No network I/O.

Only edits the marked package blocks, three plist selections and the privacy path
in Runner.xcodeproj, plus one ignored xcconfig. Run from any working directory.
"""
import argparse
from pathlib import Path
import plistlib
import re

ROOT = Path(__file__).resolve().parents[1]
PROJECT = Path("Runner.xcodeproj/project.pbxproj")
CONFIG = Path("Flutter/Publisher.generated.xcconfig")
CONFIG_TEXT = "// Generated by Publisher/configure.py --enable; do not commit.\nOTHER_SWIFT_FLAGS = $(inherited) -D IOS_PHONE_PUBLISHING\n"
PREFIX = "A117000000000000000000"
PRODUCTS = [("HaishinKit", "01", "11", "21"),
            ("RTMPHaishinKit", "01", "12", "22"),
            ("Logboard", "02", "13", "23")]


def block(label, body):
    return f"/* HADAYAH_PUBLISHER_{label}_BEGIN */\n{body}/* HADAYAH_PUBLISHER_{label}_END */\n"


def insert_once(text, anchor, addition):
    if text.count(anchor) != 1:
        raise ValueError(f"Expected exactly one project anchor: {anchor[:75]}")
    return text.replace(anchor, addition + anchor, 1)


def remove_blocks(text):
    return re.sub(r"/\* HADAYAH_PUBLISHER_(\w+)_BEGIN \*/\n.*?"
                  r"/\* HADAYAH_PUBLISHER_\1_END \*/\n", "", text, flags=re.S)


def transform(text, enabled):
    text = remove_blocks(text)
    text = text.replace("path = PublisherPrivacy/PrivacyInfo.xcprivacy;",
                        "path = PrivacyInfo.xcprivacy;")
    text = text.replace("INFOPLIST_FILE = Runner/Info-Publisher.plist;",
                        "INFOPLIST_FILE = Runner/Info.plist;")
    if text.count("INFOPLIST_FILE = Runner/Info.plist;") != 3:
        raise ValueError("Expected exactly three Runner plist settings; inspect project before toggling")
    if text.count("path = PrivacyInfo.xcprivacy;") != 1:
        raise ValueError("Expected exactly one app privacy manifest")
    if "HADAYAH_PUBLISHER_" in text:
        raise ValueError("Malformed publisher markers; inspect project before toggling")
    if not enabled:
        return text
    if any(value in text for value in ["XCRemoteSwiftPackageReference", "packageProductDependencies", "packageReferences", PREFIX]):
        raise ValueError("Existing Swift packages or reserved IDs need review before enabling")
    text = text.replace("path = PrivacyInfo.xcprivacy;",
                        "path = PublisherPrivacy/PrivacyInfo.xcprivacy;")
    text = text.replace("INFOPLIST_FILE = Runner/Info.plist;",
                        "INFOPLIST_FILE = Runner/Info-Publisher.plist;")
    builds = "".join(f"\t\t{PREFIX}{build} /* {name} in Frameworks */ = "
                     f"{{isa = PBXBuildFile; productRef = {PREFIX}{product}; }};\n"
                     for name, _, product, build in PRODUCTS)
    text = insert_once(text, "/* End PBXBuildFile section */", block("BUILDS", builds))
    objects = ""
    for suffix, name, url, version in [
        ("01", "HaishinKit", "https://github.com/HaishinKit/HaishinKit.swift", "2.2.5"),
        ("02", "Logboard", "https://github.com/shogo4405/Logboard", "2.6.0"),
    ]:
        objects += (f'\t\t{PREFIX}{suffix} /* {name} */ = {{isa = XCRemoteSwiftPackageReference; '
                    f'repositoryURL = "{url}"; requirement = {{kind = exactVersion; version = {version}; }}; }};\n')
    objects += "".join(f'\t\t{PREFIX}{product} /* {name} */ = {{isa = XCSwiftPackageProductDependency; '
                       f'package = {PREFIX}{package}; productName = {name}; }};\n'
                       for name, package, product, _ in PRODUCTS)
    text = insert_once(text, "/* Begin XCBuildConfiguration section */", block("OBJECTS", objects))
    framework_anchor = ("\t\t97C146EB1CF9000F007C117D /* Frameworks */ = {\n"
                        "\t\t\tisa = PBXFrameworksBuildPhase;\n\t\t\tbuildActionMask = 2147483647;\n\t\t\tfiles = (\n")
    if text.count(framework_anchor) != 1:
        raise ValueError("Frameworks phase changed; inspect project before toggling")
    text = text.replace(framework_anchor, framework_anchor + block("FRAMEWORKS", "".join(
        f"\t\t\t\t{PREFIX}{build} /* {name} in Frameworks */,\n" for name, _, _, build in PRODUCTS)), 1)
    text = insert_once(text, "\t\t\tproductName = Runner;", block("PRODUCTS",
        "\t\t\tpackageProductDependencies = (\n" + "".join(
            f"\t\t\t\t{PREFIX}{product} /* {name} */,\n" for name, _, product, _ in PRODUCTS) + "\t\t\t);\n"))
    text = insert_once(text, '\t\t\tprojectDirPath = "";', block("PACKAGES",
        f"\t\t\tpackageReferences = ({PREFIX}01, {PREFIX}02);\n"))
    return text


def validate_plists(root):
    with (root / "Runner/Info.plist").open("rb") as file:
        base = plistlib.load(file)
    with (root / "Runner/Info-Publisher.plist").open("rb") as file:
        publisher = plistlib.load(file)
    extra = {"NSCameraUsageDescription", "NSMicrophoneUsageDescription", "UIBackgroundModes"}
    if set(publisher) - set(base) != extra or {k: v for k, v in publisher.items() if k not in extra} != base:
        raise ValueError("Publisher plist must mirror viewer plist with only camera/mic/audio additions")
    if publisher["UIBackgroundModes"] != ["audio"]:
        raise ValueError("Only audio background mode is authorized")


def configure(root, enabled):
    root = root.resolve()
    for relative in [PROJECT, CONFIG]:
        if not (root / relative).resolve().is_relative_to(root):
            raise ValueError("Publisher target escapes the iOS directory")
    validate_plists(root)
    path = root / PROJECT
    raw = path.read_bytes()
    newline = "\r\n" if b"\r\n" in raw else "\n"
    text = raw.decode("utf-8").replace("\r\n", "\n")
    config = root / CONFIG
    if config.exists() and config.read_text(encoding="utf-8") != CONFIG_TEXT:
        raise ValueError("Refusing to overwrite an unmanaged publisher xcconfig")
    updated = transform(text, enabled).replace("\n", newline).encode("utf-8")
    if updated != raw:
        path.write_bytes(updated)
    if enabled:
        with config.open("w", encoding="utf-8", newline="\n") as file:
            file.write(CONFIG_TEXT)
    elif config.exists():
        config.unlink()  # One verified generated file; no recursive removal.


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    choice = parser.add_mutually_exclusive_group(required=True)
    choice.add_argument("--enable", action="store_true")
    choice.add_argument("--disable", action="store_true")
    args = parser.parse_args()
    configure(ROOT, args.enable)
    print("Publisher enabled: pod install, then build with IOS_PHONE_PUBLISHING=true."
          if args.enable else "Publisher disabled: run pod install, then build without the Dart flag.")
