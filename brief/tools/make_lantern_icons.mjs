// Builds the Lantern and Arch icon set from brief/tools/lantern_icons.json:
// one SVG per icon in project/assets/lantern/icons/ and the Dart enum in
// project/lib/core/widgets/lantern/lantern_glyphs.dart.
//
// The first 67 icons are the design's own (24 grid, 1.75 stroke, round caps;
// "Hedayah New Identity", App identity tab). The rest were added in the same
// hand for controls the app has and the design sheet does not draw.
//
// Run from the repository root: node brief/tools/make_lantern_icons.mjs
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';

const icons = JSON.parse(readFileSync('brief/tools/lantern_icons.json', 'utf8'));
const dir = 'project/assets/lantern/icons';
mkdirSync(dir, { recursive: true });
for (const f of readdirSync(dir)) rmSync(`${dir}/${f}`);

const names = Object.keys(icons);
for (const name of names) {
  if (!/^[a-z][a-z0-9]*$/.test(name)) throw new Error(`Bad icon name: ${name}`);
  const body = icons[name]
    .replaceAll('class="f"', 'fill="#000" stroke="none"')
    .replaceAll('class="n"', 'fill="none"');
  writeFileSync(
    `${dir}/${name}.svg`,
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${body}</svg>\n`,
  );
}

writeFileSync(
  'project/lib/core/widgets/lantern/lantern_glyphs.dart',
  `// Generated by brief/tools/make_lantern_icons.mjs from\n// brief/tools/lantern_icons.json. Do not edit.\n\n/// The Lantern and Arch icons, one SVG each in assets/lantern/icons/.\nenum LGlyph {\n${names.map((n) => `  ${n}`).join(',\n')}\n}\n`,
);
console.log(`${names.length} icons written to ${dir}`);
